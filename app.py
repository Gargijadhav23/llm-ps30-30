import os, io, time
import streamlit as st
from dotenv import load_dotenv
from openai import OpenAI
from docx import Document

load_dotenv()
client = OpenAI(api_key=os.getenv("GROQ_API_KEY"),
                base_url="https://api.groq.com/openai/v1")

MODELS = ["openai/gpt-oss-120b", "openai/gpt-oss-20b", "qwen/qwen3.8-27b"]

PROMPT = """You are an experienced school teacher. Create a {duration}-minute lesson plan.
Topic: {topic}
Grade: {grade}

Use EXACTLY these sections with time in minutes per activity (total = {duration}):
1. Learning Objectives (3 measurable points)
2. Materials Needed
3. Introduction / Hook (time)
4. Main Activities (2-3 activities, each with time and steps)
5. Assessment (quick check questions or activity, time)
6. Conclusion & Homework (time)
Keep language simple and age-appropriate for the grade.
Double-check that the times sum to exactly {duration} minutes."""

st.title("📚 Lesson Plan Generator")
topic = st.text_input("Topic", "Photosynthesis")
grade = st.selectbox("Grade", [f"Grade {i}" for i in range(1, 13)], index=6)
duration = st.number_input("Duration (minutes)", 20, 90, 40, step=5)

if st.button("Generate") and topic.strip():
    with st.spinner("Generating..."):
        done = False
        for model in MODELS:
            for attempt in range(2):
                try:
                    r = client.chat.completions.create(
                        model=model,
                        messages=[{"role": "user", "content": PROMPT.format(
                            topic=topic, grade=grade, duration=duration)}])
                    st.session_state["plan"] = r.choices[0].message.content
                    st.session_state["meta"] = f"{topic} ({grade})"
                    st.session_state["model"] = model
                    done = True
                    break
                except Exception as e:
                    if "503" in str(e) or "429" in str(e):
                        time.sleep(3)
                    else:
                        st.error(f"{model}: {e}")
                        break
            if done:
                break
        if not done:
            st.error("All models failed. Check the errors above or try again soon.")

if "plan" in st.session_state:
    plan = st.session_state["plan"]
    meta = st.session_state.get("meta", "Lesson Plan")
    st.markdown(plan)
    st.caption(f"Generated by {st.session_state.get('model', MODELS[0])} via Groq")
    st.download_button("Download .txt", plan, "lesson_plan.txt")

    doc = Document()
    doc.add_heading(f"Lesson Plan: {meta}", 1)
    for line in plan.split("\n"):
        doc.add_paragraph(line.replace("**", "").replace("#", "").strip())
    buf = io.BytesIO()
    doc.save(buf)
    st.download_button("Download .docx", buf.getvalue(), "lesson_plan.docx")